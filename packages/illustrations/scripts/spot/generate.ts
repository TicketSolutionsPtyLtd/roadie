import { execFileSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync
} from 'node:fs'
import { basename, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { check, layersOf, styleWarnings } from './check.ts'

const SPOT = fileURLToPath(new URL('../../src/spot/', import.meta.url))
export const SVGS = join(SPOT, 'svgs')
const MODULES = join(SPOT, 'illustrations')
const BARREL = join(SPOT, 'index.ts')

export const componentName = (slug: string) =>
  slug.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())

const PRINT_WIDTH = 80
const HEADER =
  '// Generated by `pnpm spot:generate`. Edit the SVG in svgs/, not this file.'

function moduleFor(slug: string, svg: string) {
  const name = componentName(slug)
  const all = layersOf(svg)
  // Laid out as oxfmt would, so the drift test compares files exactly.
  const opening = `export const ${name} = createSpotIllustration('${name}', [`
  const wrapped = opening.length > PRINT_WIDTH
  const indent = wrapped ? '    ' : '  '
  const layers = all
    .map(({ name: layer, d }, i) => {
      const line = `${indent}['${layer.toLowerCase()}', '${d}']`
      const comma = i < all.length - 1 ? 1 : 0
      return line.length + comma <= PRINT_WIDTH
        ? line
        : `${indent}[\n${indent}  '${layer.toLowerCase()}',\n${indent}  '${d}'\n${indent}]`
    })
    .join(',\n')
  const call = wrapped
    ? `export const ${name} = createSpotIllustration(\n  '${name}',\n  [\n${layers}\n  ]\n)`
    : `${opening}\n${layers}\n])`
  return `${HEADER}
import { createSpotIllustration } from '../SpotIllustration'

/** The ${slug.replaceAll('-', ' ')} spot illustration, from \`svgs/${slug}.svg\`. */
${call}
`
}

function barrelFor(slugs: string[]) {
  const exports = slugs.map((slug) => {
    const name = componentName(slug)
    return `export { ${name} } from './illustrations/${name}'`
  })
  return `${HEADER}
export {
  SpotIllustration,
  type SpotIllustrationComponentProps,
  type SpotIllustrationLayer,
  type SpotIllustrationLayers,
  type SpotIllustrationProps
} from './SpotIllustration'

${exports.join('\n')}
`
}

export function sources() {
  return readdirSync(SVGS)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((file) => ({
      file,
      slug: basename(file, '.svg'),
      svg: readFileSync(join(SVGS, file), 'utf8')
    }))
}

const EXPORTED = new Set(['SpotIllustration'])

/** Sources whose component names collide with each other or the barrel's exports. */
export function nameClashes(slugs: string[]) {
  const slugByName = new Map<string, string>()
  const clashes: string[] = []
  for (const slug of slugs) {
    const name = componentName(slug)
    const taken = slugByName.get(name)
    if (taken)
      clashes.push(
        `${taken}.svg and ${slug}.svg would both be ${name}; rename one`
      )
    else if (EXPORTED.has(name))
      clashes.push(
        `${slug}.svg would be ${name}, which the package already exports; rename it`
      )
    slugByName.set(name, slug)
  }
  return clashes
}

/** Every generated file and its contents, or the checks each source failed. */
export function generate(all = sources()) {
  const failures = [
    ...all.flatMap(({ file, svg }) =>
      check(svg, file).map((e) => `${file}: ${e}`)
    ),
    ...nameClashes(all.map((s) => s.slug))
  ]
  const files = new Map<string, string>(
    all.map(({ slug, svg }) => [
      join(MODULES, `${componentName(slug)}.ts`),
      moduleFor(slug, svg)
    ])
  )
  files.set(BARREL, barrelFor(all.map((s) => s.slug)))
  const warnings = failures.length
    ? []
    : all.flatMap(({ file, slug, svg }) =>
        styleWarnings(layersOf(svg), slug).map((w) => `${file}: ${w.message}`)
      )
  return { files, failures, warnings }
}

export function stale(files: Map<string, string>) {
  if (!existsSync(MODULES)) return []
  return readdirSync(MODULES)
    .map((f) => join(MODULES, f))
    .filter((f) => !files.has(f))
}

if (import.meta.main) {
  const { files, failures, warnings } = generate()
  if (failures.length) {
    console.error(
      `These sources don't match the spot illustration format:\n${failures.map((f) => `  ${f}`).join('\n')}`
    )
    process.exit(1)
  }
  mkdirSync(MODULES, { recursive: true })
  for (const f of stale(files)) rmSync(f)
  for (const [path, contents] of files) writeFileSync(path, contents)
  execFileSync('pnpm', ['exec', 'oxfmt', ...files.keys()], { stdio: 'inherit' })
  console.log(`Generated ${files.size - 1} spot illustrations.`)
  if (warnings.length)
    console.warn(
      `These stray from how the set is drawn; look at them in spot:preview:\n${warnings.map((w) => `  ${w}`).join('\n')}`
    )
}
