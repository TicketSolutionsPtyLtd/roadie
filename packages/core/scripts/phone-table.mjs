import { Metadata } from 'libphonenumber-js/core'
// Writes src/phone/table.ts from libphonenumber's metadata, which is a dev
// dependency only: the table is the few facts the browser needs, so the
// library itself never ships. Run `node scripts/phone-table.mjs` after bumping
// libphonenumber-js.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'

const require = createRequire(import.meta.url)
const metadata = require('libphonenumber-js/metadata.min.json')
const { version } = JSON.parse(
  readFileSync(require.resolve('libphonenumber-js/package.json'), 'utf8')
)

// Countries whose numbers formatPhone groups. Each one adds its patterns to
// every bundle that imports the phone module, so the list stays short.
export const GROUPED_COUNTRIES = ['AU', 'NZ']

const planOf = (country) => {
  const plan = new Metadata(metadata)
  plan.selectNumberingPlan(country)
  return plan.numberingPlan
}

// A small seeded generator, so the same metadata always writes the same table.
function digitSource(seed) {
  let state = seed
  return () => {
    state = (state * 1664525 + 1013904223) % 2 ** 32
    return String(state % 10)
  }
}

// Whether a real national number can begin with the trunk prefix, as Gabon's
// and Russia's can. Probed against the country's own pattern, since reading
// that out of a regex isn't practical.
function numbersStartWithTrunk(plan, trunk, lengths) {
  const pattern = new RegExp(`^(?:${plan.nationalNumberPattern()})$`)
  const nextDigit = digitSource(lengths.length + trunk.length)
  return lengths.some((length) => {
    const rest = length - trunk.length
    if (rest < 1) return false
    for (let attempt = 0; attempt < 2000; attempt++) {
      const filler =
        attempt < 10
          ? String(attempt).repeat(rest)
          : Array.from({ length: rest }, nextDigit).join('')
      if (pattern.test(trunk + filler)) return true
    }
    return false
  })
}

/** One row per country: code, dial code, each national length as a base 36 digit, and the trunk prefix, with `!` where numbers can start with it. */
export function phoneRows() {
  const rows = []
  // Each dial code's main country comes first; the runtime relies on it.
  for (const [dialCode, countries] of Object.entries(
    metadata.country_calling_codes
  )) {
    // libphonenumber judges a shared dial code by its main country's lengths,
    // so Jersey's numbers are measured as the United Kingdom's are.
    const lengths = planOf(countries[0]).possibleLengths()
    for (const country of countries) {
      if (!metadata.countries[country]) continue
      const plan = planOf(country)
      // The metadata holds 0, not a string, where a country has no prefix.
      const prefix = plan.nationalPrefix()
      const trunk = typeof prefix === 'string' ? prefix : ''
      rows.push(
        [
          country,
          dialCode,
          lengths.map((length) => length.toString(36)).join(''),
          trunk && numbersStartWithTrunk(plan, trunk, lengths)
            ? `${trunk}!`
            : trunk
        ].join(',')
      )
    }
  }
  return rows
}

/** One row per pattern of each grouped country: code, the digits, how to group them, what they start with, and the national form of the first group. */
export function phoneFormatRows() {
  return GROUPED_COUNTRIES.flatMap((country) =>
    planOf(country)
      .formats()
      .map((format) =>
        [
          country,
          format.pattern(),
          format.format(),
          format.leadingDigitsPatterns().at(-1) ?? '',
          format.usesNationalPrefix()
            ? format.nationalPrefixFormattingRule()
            : ''
        ].join('~')
      )
  )
}

export function phoneTableSource() {
  return [
    `// Generated by scripts/phone-table.mjs from libphonenumber-js ${version}. Don't edit by hand.`,
    '',
    "/** `code,dialCode,lengths,trunk` per country, each dial code's main country first. A length is a base 36 digit, and `!` marks a trunk prefix real numbers can start with. */",
    'export const PHONE_TABLE =',
    `  '${phoneRows().join(';')}'`,
    '',
    '/** `code~pattern~groups~leading digits~national first group` per pattern, for the countries formatPhone groups. */',
    `export const PHONE_FORMATS = String.raw\`${phoneFormatRows().join(';')}\``,
    ''
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(
    new URL('../src/phone/table.ts', import.meta.url),
    phoneTableSource()
  )
}
